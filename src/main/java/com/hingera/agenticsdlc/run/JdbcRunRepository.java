package com.hingera.agenticsdlc.run;

import com.fasterxml.jackson.core.JsonProcessingException;
import com.fasterxml.jackson.core.type.TypeReference;
import com.fasterxml.jackson.databind.ObjectMapper;
import jakarta.annotation.PostConstruct;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Repository;
import org.springframework.transaction.annotation.Transactional;

import javax.crypto.Mac;
import javax.crypto.spec.SecretKeySpec;
import java.nio.charset.StandardCharsets;
import java.security.GeneralSecurityException;
import java.security.MessageDigest;
import java.util.ArrayList;
import java.util.HexFormat;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.UUID;

@Repository
public class JdbcRunRepository implements RunRepository {
    private static final TypeReference<Map<String, String>> STRING_MAP = new TypeReference<>() { };
    private static final TypeReference<Set<String>> STRING_SET = new TypeReference<>() { };
    private static final String GENESIS_HASH = "0".repeat(64);

    private final JdbcTemplate jdbcTemplate;
    private final ObjectMapper objectMapper;
    private final byte[] auditKey;

    public JdbcRunRepository(JdbcTemplate jdbcTemplate, ObjectMapper objectMapper,
                             @Value("${agentic.audit.key:}") String auditKey) {
        if (auditKey == null || auditKey.getBytes(StandardCharsets.UTF_8).length < 32) {
            throw new IllegalStateException("Configure AGENTIC_SDLC_AUDIT_KEY with at least 32 bytes");
        }
        this.jdbcTemplate = jdbcTemplate;
        this.objectMapper = objectMapper;
        this.auditKey = auditKey.getBytes(StandardCharsets.UTF_8);
    }

    @PostConstruct
    public void initializeSchema() {
        jdbcTemplate.execute("""
                CREATE TABLE IF NOT EXISTS sdlc_runs (
                    run_id VARCHAR(36) PRIMARY KEY,
                    run_json CLOB NOT NULL,
                    workflow_json CLOB NOT NULL,
                    audit_tip VARCHAR(64) NOT NULL
                )
                """);
        jdbcTemplate.execute("""
                CREATE TABLE IF NOT EXISTS sdlc_run_events (
                    sequence_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    event_id VARCHAR(36) NOT NULL UNIQUE,
                    run_id VARCHAR(36) NOT NULL,
                    event_json CLOB NOT NULL,
                    previous_hash VARCHAR(64) NOT NULL,
                    event_hash VARCHAR(64) NOT NULL,
                    CONSTRAINT fk_sdlc_run_events_run FOREIGN KEY (run_id) REFERENCES sdlc_runs(run_id)
                )
                """);
        jdbcTemplate.execute("CREATE INDEX IF NOT EXISTS idx_sdlc_events_run_sequence ON sdlc_run_events(run_id, sequence_id)");
    }

    @Override
    public List<StoredRunState> loadAll() {
        List<StoredRunState> storedRuns = new ArrayList<>();
        jdbcTemplate.query("SELECT run_id, run_json, workflow_json, audit_tip FROM sdlc_runs ORDER BY run_id", resultSet -> {
            UUID runId = UUID.fromString(resultSet.getString("run_id"));
            EngineeringRun run = read(resultSet.getString("run_json"), EngineeringRun.class);
            WorkflowSnapshot workflow = readWorkflow(resultSet.getString("workflow_json"));
            String storedAuditTip = resultSet.getString("audit_tip");
            List<AuditRow> auditRows = jdbcTemplate.query(
                    "SELECT event_json, previous_hash, event_hash FROM sdlc_run_events WHERE run_id = ? ORDER BY sequence_id",
                    (eventRow, rowNumber) -> new AuditRow(eventRow.getString("event_json"),
                            eventRow.getString("previous_hash"), eventRow.getString("event_hash")),
                    runId.toString());
            List<RunAuditEvent> events = new ArrayList<>();
            String expectedPreviousHash = GENESIS_HASH;
            for (AuditRow auditRow : auditRows) {
                String expectedHash = sign(expectedPreviousHash + ":" + auditRow.eventJson());
                if (!expectedPreviousHash.equals(auditRow.previousHash())
                        || !MessageDigest.isEqual(expectedHash.getBytes(StandardCharsets.US_ASCII),
                        auditRow.eventHash().getBytes(StandardCharsets.US_ASCII))) {
                    throw new IllegalStateException("Audit hash-chain verification failed for run " + runId);
                }
                events.add(read(auditRow.eventJson(), RunAuditEvent.class));
                expectedPreviousHash = auditRow.eventHash();
            }
            if (!expectedPreviousHash.equals(storedAuditTip)) {
                throw new IllegalStateException("Audit chain tip verification failed for run " + runId);
            }
            storedRuns.add(new StoredRunState(run, workflow, events));
        });
        return List.copyOf(storedRuns);
    }

    @Override
    public void saveRun(EngineeringRun run) {
        String runId = run.id().toString();
        String runJson = write(run);
        int updated = jdbcTemplate.update("UPDATE sdlc_runs SET run_json = ? WHERE run_id = ?", runJson, runId);
        if (updated == 0) {
            jdbcTemplate.update("INSERT INTO sdlc_runs (run_id, run_json, workflow_json, audit_tip) VALUES (?, ?, ?, ?)",
                    runId, runJson, write(new WorkflowSnapshot(null, null, null, null)), GENESIS_HASH);
        }
    }

    @Override
    @Transactional
    public void appendEvent(RunAuditEvent event, WorkflowSnapshot workflow) {
        String previousHash = jdbcTemplate.query(
                "SELECT event_hash FROM sdlc_run_events WHERE run_id = ? ORDER BY sequence_id DESC LIMIT 1",
                resultSet -> resultSet.next() ? resultSet.getString(1) : GENESIS_HASH,
                event.runId().toString());
        String eventJson = write(event);
        String eventHash = sign(previousHash + ":" + eventJson);
        jdbcTemplate.update("""
                INSERT INTO sdlc_run_events (event_id, run_id, event_json, previous_hash, event_hash)
                VALUES (?, ?, ?, ?, ?)
                """, event.eventId().toString(), event.runId().toString(), eventJson, previousHash, eventHash);
        int updated = jdbcTemplate.update("UPDATE sdlc_runs SET workflow_json = ?, audit_tip = ? WHERE run_id = ?",
                write(workflow), eventHash, event.runId().toString());
        if (updated != 1) {
            throw new IllegalStateException("Cannot persist workflow state for missing run " + event.runId());
        }
    }

    private WorkflowSnapshot readWorkflow(String json) {
        try {
            Map<String, Object> values = objectMapper.readValue(json, new TypeReference<>() { });
            Map<String, String> stageStates = objectMapper.convertValue(values.get("stageStates"), STRING_MAP);
            Set<String> approvedStages = objectMapper.convertValue(values.get("approvedStages"), STRING_SET);
            Map<String, String> stageOutputs = objectMapper.convertValue(values.get("stageOutputs"), STRING_MAP);
            String pendingApproval = (String) values.get("pendingApproval");
            return new WorkflowSnapshot(stageStates, pendingApproval, approvedStages, stageOutputs);
        } catch (JsonProcessingException failure) {
            throw new IllegalStateException("Unable to read persisted workflow state", failure);
        }
    }

    private <T> T read(String json, Class<T> type) {
        try {
            return objectMapper.readValue(json, type);
        } catch (JsonProcessingException failure) {
            throw new IllegalStateException("Unable to read persisted " + type.getSimpleName(), failure);
        }
    }

    private String write(Object value) {
        try {
            return objectMapper.writeValueAsString(value);
        } catch (JsonProcessingException failure) {
            throw new IllegalStateException("Unable to serialize persistent run state", failure);
        }
    }

    private String sign(String value) {
        try {
            Mac mac = Mac.getInstance("HmacSHA256");
            mac.init(new SecretKeySpec(auditKey, "HmacSHA256"));
            return HexFormat.of().formatHex(mac.doFinal(value.getBytes(StandardCharsets.UTF_8)));
        } catch (GeneralSecurityException failure) {
            throw new IllegalStateException("Unable to sign audit event", failure);
        }
    }

    private record AuditRow(String eventJson, String previousHash, String eventHash) { }
}
